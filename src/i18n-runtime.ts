/**
 * Locale runtime: registry, BCP-47 matching, fallback chain, ICU rendering.
 *
 * The registry is the single source of truth (audit §7.5: Core owns it, Desk gets a
 * copy; `test/i18n-contract.test.mjs` asserts the two hashes match). Every language's
 * siblings, so nothing parses ICU in the renderer.
 *
 * Matching uses `Intl.Locale#maximize`, not the old region regex: `zh-HK` maximises to
 * `zh-Hant-HK` and therefore matches `zh-Hant`, while bare `zh` maximises to
 * `zh-Hans-CN`. Adding Japanese or Korean needs one registry record and one folder,
 * not a new branch in the matcher.
 *
 * Fallback never crosses writing systems (Jeff decision Q2): zh-Hant -> en, not
 * zh-Hant -> zh-Hans. A missing key shows the key itself so it is visible in review,
 * never a silent empty string.
 */
import registry from "./locales/registry.json" with { type: "json" };
import enWs from "./locales/en/ws.json" with { type: "json" };
import enVg from "./locales/en/vg.json" with { type: "json" };
import enCommon from "./locales/en/common.json" with { type: "json" };
import hansWs from "./locales/zh-Hans/ws.json" with { type: "json" };
import hansVg from "./locales/zh-Hans/vg.json" with { type: "json" };
import hansCommon from "./locales/zh-Hans/common.json" with { type: "json" };
import hantWs from "./locales/zh-Hant/ws.json" with { type: "json" };
import hantVg from "./locales/zh-Hant/vg.json" with { type: "json" };
import hantCommon from "./locales/zh-Hant/common.json" with { type: "json" };
import complexIndex from "./locales/complex.json" with { type: "json" };

export type Locale = "en" | "zh-Hans" | "zh-Hant";
export type LocalePreference = Locale | "system";
export type LanguageStatus = "stable" | "beta" | "hidden";

export interface LanguageRecord {
  tag: Locale;
  nativeName: string;
  status: LanguageStatus;
  dir: "ltr" | "rtl";
  font: string;
  match: readonly { language: string; script: string | null }[];
  fallback: readonly Locale[];
}

export const LANGUAGES = registry.languages as readonly LanguageRecord[];
export const NAMESPACES = registry.namespaces as readonly string[];
export const BASELINE_LOCALE: Locale = registry.baseline as Locale;

const TEXTS: Record<Locale, Record<string, Record<string, string>>> = {
  en: { ws: enWs, vg: enVg, common: enCommon },
  "zh-Hans": { ws: hansWs, vg: hansVg, common: hansCommon },
  "zh-Hant": { ws: hantWs, vg: hantVg, common: hantCommon },
};
/**
 * Keys whose copy needs real ICU syntax (plural/select). Everything else is plain
 * `{name}` interpolation and takes the fast path, which keeps the shipped bundle near
 * the pre-B0 size. Generated by `scripts/build-i18n-ast.mjs`, asserted by the contract
 * test.
 */
const COMPLEX = new Set((complexIndex as { lang: string; ns: string; key: string }[]).map(entry => `${entry.lang} ${entry.key}`));

/**
 * Set by `installComplexFormat` when the build actually contains complex messages.
 * Keeping the import behind this hook means today's all-plain catalogue ships without
 * the ICU parser; the contract test wires it up so plural/select stays covered.
 */
let formatComplex: ((text: string, locale: Locale, values: Record<string, string | number>) => string) | null = null;

export function installComplexFormat(renderer: typeof formatComplex): void { formatComplex = renderer; }

export function isLocale(value: unknown): value is Locale {
  return typeof value === "string" && LANGUAGES.some(language => language.tag === value);
}

/**
 * Accepts the legacy `"zh"` alias (still passed by the frozen rollback entry) and any
 * BCP-47 tag the registry can match. Everything else falls back to English.
 */
export function toLocale(value: unknown): Locale {
  if (value === "zh") return "zh-Hans";
  if (isLocale(value)) return value;
  const matched = matchLanguageTag(typeof value === "string" ? value : null);
  return matched ?? BASELINE_LOCALE;
}

/** Languages a picker may offer. beta stays hidden until the Traditional review lands. */
export function selectableLanguages(): readonly LanguageRecord[] {
  return LANGUAGES.filter(language => language.status === "stable" && language.tag !== BASELINE_LOCALE
    ? true : language.tag === BASELINE_LOCALE);
}

/** `system` resolves to the first supported system preference, else English. */
export function resolveLocale(preference: LocalePreference): Locale {
  return preference === "system" ? detectSystemLocale() : preference;
}

export function detectSystemLocale(): Locale {
  const languages = globalThis.navigator?.languages;
  return localeFromLanguages(languages?.length ? languages : [globalThis.navigator?.language ?? "en"]);
}

/** First language tag the registry can match; unknown tags fall through to English. */
export function localeFromLanguages(languages: readonly string[]): Locale {
  for (const value of languages) {
    const tag = matchLanguageTag(value);
    if (tag) return tag;
  }
  return BASELINE_LOCALE;
}

/**
 * Match a BCP-47 tag against the registry using `Intl.Locale#maximize`.
 * `zh-HK` -> `zh-Hant-HK` (matches zh-Hant), `zh` -> `zh-Hans-CN` (matches zh-Hans),
 * `en-GB` -> `en-Latn-GB` (matches en). The explicit script always wins over region.
 */
export function matchLanguageTag(value: string | null | undefined): Locale | null {
  const cleaned = String(value ?? "").trim().replace(/_/g, "-");
  if (!cleaned) return null;
  let language: string;
  let script: string | null;
  try {
    const maximized = new Intl.Locale(cleaned).maximize();
    language = maximized.language;
    script = maximized.script || null;
  } catch {
    const parts = cleaned.toLowerCase().split("-");
    language = parts[0] ?? "";
    const raw = parts.slice(1).find(part => part.length === 4 && !/\d/.test(part));
    script = raw ? raw[0].toUpperCase() + raw.slice(1).toLowerCase() : null;
  }
  for (const record of LANGUAGES) {
    for (const candidate of record.match) {
      if (candidate.language !== language) continue;
      if (candidate.script === null) return record.tag;
      if (candidate.script === script) return record.tag;
    }
  }
  return null;
}

/** Lookup order: requested locale, then its fallback chain, then English. */
export function localeChain(locale: Locale): Locale[] {
  const record = LANGUAGES.find(language => language.tag === locale);
  const chain: Locale[] = [locale, ...(record?.fallback ?? [])];
  if (!chain.includes(BASELINE_LOCALE)) chain.push(BASELINE_LOCALE);
  return chain;
}

export function messageText(locale: Locale | "zh" | string, key: string): string {
  for (const step of localeChain(toLocale(locale))) {
    const namespace = key.split(".")[0];
    const text = TEXTS[step]?.[namespace]?.[key];
    if (typeof text === "string") return text;
  }
  return key;
}

/** True when this key needs ICU formatting rather than plain interpolation. */
export function isComplexMessage(locale: Locale | "zh" | string, key: string): boolean {
  return localeChain(toLocale(locale)).some(step => COMPLEX.has(`${step} ${key}`));
}

/**
 * Render a message. Plain messages interpolate directly (identical result, no parser
 * cost); only keys listed in `locales/complex.json` go through IntlMessageFormat.
 */
export function formatMessage(locale: Locale | "zh" | string, key: string, values: Record<string, string | number> = {}): string {
  const normalized = toLocale(locale);
  const text = messageText(normalized, key);
  const substitute = (source: string) => source.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : match);
  if (!isComplexMessage(normalized, key) || !formatComplex) {
    // No complex messages shipped yet: the ICU parser is not even in the bundle.
    return substitute(text);
  }
  try { return formatComplex(text, normalized, values); }
  catch { return substitute(text); }
}

/**
 * Keep `<html lang>` in step with the renderer language.
 *
 * The shell sets `lang` on its own root for font selection, but boot screens, portals
 * and native input-method behaviour read the document language. Audit §2 calls this out
 * as a correctness issue (VoiceOver pronunciation, spell-check, IME hints), so the
 * change is applied whenever the chosen locale changes, and unset only when there is no
 * document (tests, node).
 */
export function applyDocumentLanguage(locale: Locale): void {
  const root = globalThis.document?.documentElement;
  if (!root) return;
  root.lang = locale;
  const record = LANGUAGES.find(language => language.tag === locale);
  if (record) root.dir = record.dir;
}

/**
 * Join a list for inline display (audit §7.6). Chinese uses the ideographic comma, which
 * is what `zh ? "、" : ", "` produced; English keeps the plain comma join so this is not a
 * behaviour change. A future ICU `ListFormat` upgrade can revisit the English "and".
 */
export function formatList(locale: Locale | "zh" | string, values: readonly string[]): string {
  const joined = toLocale(locale);
  return joined === "zh-Hans" || joined === "zh-Hant" ? values.join("、") : values.join(", ");
}

/** All keys in the English baseline (the source of the `Key` type). */
export function baselineKeys(): string[] {
  return NAMESPACES.flatMap(namespace => Object.keys(TEXTS[BASELINE_LOCALE][namespace] ?? {}));
}
