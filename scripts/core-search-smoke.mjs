import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
const core=path.resolve(process.argv[2]),workspace=path.resolve(process.argv[3]);
assert(!fs.existsSync(workspace));fs.mkdirSync(workspace,{recursive:true,mode:0o700});
const {zvecAvailable}=await import(pathToFileURL(path.join(core,'dist/search/zvec-store.js')));
const {chunkText,buildIndex,queryIndex}=await import(pathToFileURL(path.join(core,'dist/search/semindex.js')));
const available=await zvecAvailable();
if(process.platform==='darwin'&&process.arch==='x64')assert.equal(available,false,'Intel must use the existing JSON fallback without unsupported bindings');
fs.writeFileSync(path.join(workspace,'package.json'),'{}\n');
const text='function renderButton() { return button; }\n',file='ui.ts';
fs.writeFileSync(path.join(workspace,file),text);
const embed=async texts=>texts.map(()=>[1,0,0]);
const chunks=chunkText(text,file,'repo');
assert(chunks.length>0);const built=await buildIndex('repo',chunks,embed,workspace);
assert.equal(built.total,chunks.length);const hits=await queryIndex('repo','button',embed,workspace,1);
assert.equal(hits[0]?.file,file);assert.equal(hits[0]?.score,1);
console.log(JSON.stringify({platform:process.platform,arch:process.arch,zvecAvailable:available,backend:available?'native-or-json':'json-fallback',hits:hits.length,modelRequests:0}));
