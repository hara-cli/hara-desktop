#!/usr/bin/env node
/**
 * src/assets/mascot/*.svg  ->  src/generated/hara-mascot-assets.ts
 * The SVGs are the source (uiux mascot final, 2026-11-09). Re-run after replacing any of them;
 * test/hara-mascot.test.mjs fails when the generated module is stale.
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export function mascotAssetsModule() {
  const dir = path.join(root, "src/assets/mascot");
  const entries = readdirSync(dir).filter(name => name.endsWith(".svg")).sort()
    .map(name => `  ${JSON.stringify(name.replace(/^hara-gate-/, "").replace(/\.svg$/, ""))}: ${JSON.stringify(readFileSync(path.join(dir, name), "utf8").trim())},`);
  return `// Generated by scripts/build-mascot-assets.mjs from src/assets/mascot/*.svg. Do not edit.\nexport const MASCOT_SVG: Readonly<Record<string, string>> = {\n${entries.join("\n")}\n};\n`;
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(path.join(root, "src/generated/hara-mascot-assets.ts"), mascotAssetsModule());
  console.log("mascot: generated src/generated/hara-mascot-assets.ts");
}
