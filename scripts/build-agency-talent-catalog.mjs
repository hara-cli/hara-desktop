#!/usr/bin/env node
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { basename, dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const PINNED_REVISION = "ebe9c99acb5c96f9468de368d8bead775387d1a7";
const EXPECTED_AGENT_COUNT = 270;
const scriptRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");

function option(name) {
  const index = process.argv.indexOf(name);
  return index >= 0 ? process.argv[index + 1] : undefined;
}

const sourceRoot = resolve(option("--source") ?? "");
const outputFile = resolve(option("--output") ?? join(scriptRoot, "src", "generated", "agency-agent-records.ts"));
if (!option("--source")) throw new Error("--source <agency-agents checkout> is required");

const revision = execFileSync("git", ["-C", sourceRoot, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();
if (revision !== PINNED_REVISION) {
  throw new Error(`Agency Agents checkout must be pinned to ${PINNED_REVISION}; received ${revision}`);
}

function bounded(value, cap) {
  return String(value ?? "").replace(/[\u0000-\u001f\u007f]/g, " ").replace(/\s+/g, " ").trim().slice(0, cap);
}

function scalar(raw) {
  const value = raw.trim();
  if (!value) return "";
  if (value.startsWith('"') && value.endsWith('"')) {
    try { return JSON.parse(value); } catch { return value.slice(1, -1); }
  }
  if (value.startsWith("'") && value.endsWith("'")) return value.slice(1, -1).replace(/''/g, "'");
  return value;
}

function frontmatter(markdown) {
  const match = /^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)/.exec(markdown);
  if (!match) return {};
  const metadata = {};
  for (const line of match[1].split(/\r?\n/)) {
    if (!line || /^\s/.test(line)) continue;
    const pair = /^([A-Za-z0-9_-]+)\s*:\s*(.*)$/.exec(line);
    if (pair) metadata[pair[1]] = scalar(pair[2]);
  }
  return metadata;
}

function markdownFiles(root) {
  const files = [];
  for (const entry of readdirSync(root, { withFileTypes: true }).sort((left, right) => left.name.localeCompare(right.name))) {
    const target = join(root, entry.name);
    if (entry.isDirectory()) files.push(...markdownFiles(target));
    else if (entry.isFile() && entry.name.endsWith(".md")) files.push(target);
  }
  return files;
}

const divisionManifest = JSON.parse(readFileSync(join(sourceRoot, "divisions.json"), "utf8"));
const divisionIds = Object.keys(divisionManifest.divisions ?? {}).sort();
if (!divisionIds.length) throw new Error("Agency Agents divisions manifest has no divisions map");
const records = [];
for (const division of divisionIds) {
  const divisionRoot = join(sourceRoot, division);
  for (const sourceFile of markdownFiles(divisionRoot)) {
    const filename = basename(sourceFile);
    const metadata = frontmatter(readFileSync(sourceFile, "utf8"));
    const rawStem = basename(filename, ".md");
    const stem = rawStem.startsWith(`${division}-`) ? rawStem.slice(division.length + 1) : rawStem;
    const sourcePath = relative(sourceRoot, sourceFile).split(sep).join("/");
    const nestedPath = relative(divisionRoot, dirname(sourceFile)).split(sep).filter((part) => part && part !== ".");
    const name = bounded(metadata.name || stem.replace(/[-_]+/g, " "), 100);
    const description = bounded(metadata.description, 800);
    const vibe = bounded(metadata.vibe, 400);
    if (!name || (!description && !vibe)) throw new Error(`Agent metadata is incomplete: ${sourcePath}`);
    records.push({
      id: `agency-agents/${division}/${[...nestedPath, stem].join("/")}`.toLowerCase(),
      sourcePath,
      division,
      name,
      description,
      color: bounded(metadata.color, 32),
      emoji: bounded(metadata.emoji, 24) || "✦",
      vibe,
    });
  }
}

if (records.length !== EXPECTED_AGENT_COUNT) {
  throw new Error(`Expected ${EXPECTED_AGENT_COUNT} Agency Agents, received ${records.length}`);
}
if (new Set(records.map((record) => record.id)).size !== records.length) {
  throw new Error("Generated Agency Agent ids are not unique");
}

const header = `// Generated by scripts/build-agency-talent-catalog.mjs from Agency Agents ${revision}.\n// Do not hand-edit. The pinned source is MIT licensed; its notice is exposed by talent-blueprints.ts.\n\n`;
const body = `export interface GeneratedAgencyAgentRecord {\n  id: string;\n  sourcePath: string;\n  division: string;\n  name: string;\n  description: string;\n  color: string;\n  emoji: string;\n  vibe: string;\n}\n\nexport const AGENCY_AGENT_RECORDS: readonly GeneratedAgencyAgentRecord[] = ${JSON.stringify(records, null, 2)};\n`;
mkdirSync(dirname(outputFile), { recursive: true });
writeFileSync(outputFile, header + body, { encoding: "utf8", mode: 0o644 });
process.stdout.write(`Generated ${records.length} Agency Agent records at ${outputFile}\n`);
